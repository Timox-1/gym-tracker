-- Явный флаг пропущенной тренировки
--
-- Проблема: skipWorkout создаёт сессию с completed_at и нулём подходов.
-- Расписание (getNextWorkout) от неё отталкивается — это правильно и нужно.
-- Но всё остальное считает её настоящей тренировкой:
--   • Прогресс: счётчик тренировок завышен (3 пустышки на 16.07.2026)
--   • История: пустые строки без подходов
--   • lastDataMap («прошлый раз») берёт последние 5 сессий — пустышки съедают
--     слоты, и веса аксессуаров теряются. Пропуск целой недели = 3 слота из 5.
--
-- Отличать пустышки по count(sets)=0 нельзя надёжно: брошенная на первом сете
-- тренировка тоже почти пустая, но пропуском не является. Нужен явный флаг.

begin;

alter table public.workout_sessions
  add column if not exists skipped boolean not null default false;

-- Бэкфилл: завершённые сессии без единого подхода — это пропуски.
-- На момент миграции таких три: 18.05 присед (н4/ц1), 22.05 жим (н1/ц2),
-- 12.06 становая (н4/ц2). Незавершённые (completed_at is null) не трогаем —
-- это брошенные сессии, у них другая природа.
update public.workout_sessions s
set skipped = true
where s.completed_at is not null
  and not exists (select 1 from public.sets st where st.session_id = s.id);

commit;
